#pragma once
#include <Arduino.h>

/* ============================================================================
 *  跨障碍擦玻璃机器人 —— 硬件配置 (ESP32-S3 / Arduino IDE)
 *  驱动方案：两颗 L298N，纯数字直驱，【不用 EN 脚、不用 PWM】
 *  联网方案：只用 ESP32 自建热点，手机直连
 * ----------------------------------------------------------------------------
 *  ★ L298N 直驱接法（本配置采用）
 *    EN 跳线帽保持短接 = 通道常使能 = 永远全速。
 *    IN 脚只给高低电平，不看占空比：
 *      IN1=1 IN2=0  -> 正转（全速）
 *      IN1=0 IN2=1  -> 反转（全速）
 *      IN1=1 IN2=1  -> 刹车（绕组短接，玻璃上不打滑）
 *      IN1=0 IN2=0  -> 断电滑行
 *    因为 IN 是数字口，所以电机只有 3 种状态：正转 / 反转 / 停。
 *    速度、软启停、左右轮差速微调都无法用软件实现，只能靠机械结构保证。
 *    如果以后想要调速：把 ENA/ENB 跳到空闲 GPIO 上即可（每路一根线）。
 *
 *  ★ 整个板子只有舵机用硬件 PWM（50Hz，GPIO10）
 * ----------------------------------------------------------------------------
 *  【接线表】已避开 ESP32-S3 的敏感脚：
 *      GPIO0/3/45/46  = 启动/烧录 strapping，不能占用
 *      GPIO19/20      = USB D-/D+，占用后 USB 串口就废了
 *      GPIO26~32      = 板载 Flash SPI，绝对不能用
 *      GPIO33~37      = 八线 PSRAM 模块(N16R8)被占用
 *  ----------------------------------------------------------------------------
 *  L298N 模块 1（驱动行走，两个通道都用，纯数字）
 *  ----------------------------------------------------------------------------
 *    ESP32 GPIO 4  -> IN1      OUT1 -> 左轮电机 +
 *    ESP32 GPIO 5  -> IN2      OUT2 -> 左轮电机 -
 *    ESP32 GPIO 6  -> IN3      OUT3 -> 右轮电机 +
 *    ESP32 GPIO 7  -> IN4      OUT4 -> 右轮电机 -
 *    ENA、ENB 跳线帽必须插着
 *    +12V 接电池正极，GND 接电池负极，模块 GND 必须与 ESP32 GND 相连
 *
 *  L298N 模块 2（驱动电动推杆，纯数字）
 *  ----------------------------------------------------------------------------
 *    ESP32 GPIO 15 -> IN1      OUT1 -> 推杆电机 +
 *    ESP32 GPIO 16 -> IN2      OUT2 -> 推杆电机 -
 *    ENA 跳线帽必须插着；IN3/IN4(通道B) 空着，可留给毛刷电机等备用
 *
 *  其他外设
 *  ----------------------------------------------------------------------------
 *    舵机        信号            GPIO 10     电源务必独立 5V，别从板子取
 *    真空泵      驱动脚          GPIO 11     高电平吸合
 *    继电器 1    控制脚          GPIO 12     高电平吸合（高电平启动）
 *    继电器 2    控制脚          GPIO 13     高电平吸合（高电平启动）
 *  ----------------------------------------------------------------------------
 *  共地：两个 L298N 的 GND、ESP32 GND、电池 GND 必须全部连在一起
 *  5V 输出：L298N 的 5V 输出最多只能用其中一颗给 ESP32 供电，千万不要把两颗的
 *           5V 并在一起（两个稳压器会互相灌电流发热烧掉）
 * ========================================================================== */

// ------------- L298N 模块1：左轮(A路) / 右轮(B路)，EN 跳线帽常闭 --------------
#define PIN_M_LEFT_IN1    4       // 左轮 IN1
#define PIN_M_LEFT_IN2    5       // 左轮 IN2
#define PIN_M_RIGHT_IN1   6       // 右轮 IN3
#define PIN_M_RIGHT_IN2   7       // 右轮 IN4

// --------------------- L298N 模块2：电动推杆，EN 跳线帽常闭 -------------------
#define PIN_ACT_IN1       15      // 推杆 IN1
#define PIN_ACT_IN2       16      // 推杆 IN2

// ------------------------------- 其他外设 -----------------------------------
#define PIN_SERVO         10
#define PIN_PUMP          11
#define PIN_RELAY1        12
#define PIN_RELAY2        13

// ------------------------------- 电机参数 -----------------------------------
// 纯数字直驱，没有速度概念，所以这里没有任何 PWM/占空比参数
#define MOTOR_STOP_BRAKE  1       // 1=停车时两 IN 拉高刹车(玻璃上不打滑) 0=全低滑行

// ------------------------------- 推杆参数 -----------------------------------
#define ACT_DEAD_MS       150     // 换向死区，先断开再反转，保护 L298N 和推杆
#define ACT_MAX_MS        25000   // 单次连续运行上限，保护推杆电机

// ------------------------------- 舵机参数（唯一的 PWM 输出）------------------
#define SERVO_FREQ        50      // 舵机标准 50Hz
#define SERVO_RES         14      // 14 位：50Hz×2^14=819kHz，LEDC 分频器很轻松
#define SERVO_CHANNEL     0       // 显式指定 LEDC 通道，避免自动分配撞车
#define SERVO_MIN_US      500
#define SERVO_MAX_US      2500
#define SERVO_DEFAULT_ANGLE 90

// ★ 转动速度：每移动 1 度停多少毫秒。数值越大越慢。
//   速度 = 1000 / SERVO_STEP_DELAY_MS 度/秒
//       20ms -> 50°/s，180° 约 3.6 秒（推荐）
//       40ms -> 25°/s，180° 约 7.2 秒（很慢，适合玻璃上精细对位）
//       10ms -> 100°/s，180° 约 1.8 秒（偏快）
#define SERVO_STEP_DELAY_MS 20

#define SERVO_BOOT_TEST   0       // 0=开机只保持初始角度不动（推荐）；1=开机自检扫一遍

// ------------------------------- 开关量输出 ---------------------------------
// 1 = 高电平吸合（高电平触发）；0 = 低电平吸合（低电平触发）
#define PUMP_ACTIVE_HIGH  1       // 真空泵：高电平吸合
#define RELAY_ACTIVE_HIGH 1       // 继电器 1/2：高电平吸合（高电平启动）

// ------------------------------- 安全参数 -----------------------------------
#define MOVE_WATCHDOG_MS  700     // 行走指令 700ms 没刷新 -> 自动停车
#define ACT_WATCHDOG_MS   800     // 推杆指令 800ms 没刷新 -> 自动停止

// ============================================================================
//                              WiFi 热点配置
// ============================================================================
// 手机连这个热点，页面自动弹出。想改名字/密码就改下面两行。
#define AP_SSID_PREFIX    "GlassBot-"   // 热点名，后面自动加 MAC 后缀区分多台
#define AP_PASSWORD       "12345678"    // 至少 8 位；填 "" 表示不加密（不推荐）
#define AP_CHANNEL        6             // 信道 1~13，被干扰就换
#define AP_MAX_CLIENTS    4             // 最多同时连几台手机
#define AP_IP             192,168,4,1   // 热点网关地址，一般不改

// 1 = 开启强制门户：手机连上热点后自动弹出控制页（安卓/iOS 都支持）
// 0 = 关闭，需要手动在浏览器输入 http://192.168.4.1
#define CAPTIVE_PORTAL    1

